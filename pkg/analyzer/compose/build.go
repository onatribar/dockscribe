package compose

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/onatribar/dockscribe/pkg/analyzer"
	"github.com/onatribar/dockscribe/pkg/parser/compose"
	"github.com/onatribar/dockscribe/pkg/parser/dockerfile"
)

// cached outcome of resolving one build.context + build.dockerfile path
type resolvedDockerfile struct {
	file    *dockerfile.File
	missing bool
}

func checkBuildReference(svc compose.Service, ctx analyzer.Context, dfCache map[string]*resolvedDockerfile) []analyzer.Finding {
	if svc.Build == nil || ctx.Dir == "" || isRemoteContext(svc.Build.Context) {
		return nil
	}

	contextDir := ctx.Dir
	if svc.Build.Context != "" {
		contextDir = filepath.Join(ctx.Dir, svc.Build.Context)
	}
	path := filepath.Join(contextDir, svc.Build.Dockerfile)

	resolved, cached := dfCache[path]
	if !cached {
		resolved = resolveDockerfile(path)
		dfCache[path] = resolved
	}

	if resolved.missing {
		return []analyzer.Finding{{
			Line:     svc.Line,
			Severity: analyzer.Warning,
			Category: analyzer.CategoryPerformance,
			RuleID:   "C010",
			Message:  fmt.Sprintf("Service %q's build.dockerfile %q was not found.", svc.Name, filepath.ToSlash(filepath.Join(svc.Build.Context, svc.Build.Dockerfile))),
			Detail:   "This path doesn't exist relative to the compose file's directory, so building this service will fail. If it's generated by a step that hasn't run yet, this is a false positive - dockscribe only sees what's on disk right now.",
		}}
	}
	if resolved.file == nil {
		return nil
	}

	var findings []analyzer.Finding
	findings = append(findings, checkBuildTarget(svc, resolved.file)...)
	findings = append(findings, checkUserOverride(svc, resolved.file)...)
	return findings
}

func resolveDockerfile(path string) *resolvedDockerfile {
	content, err := os.ReadFile(path)
	if err != nil {
		return &resolvedDockerfile{missing: true}
	}
	parsed, err := dockerfile.New().Parse(content)
	if err != nil {
		return &resolvedDockerfile{}
	}
	return &resolvedDockerfile{file: parsed.(*dockerfile.File)}
}

// Nothing to check on disk for a remote Git/URL context
func isRemoteContext(context string) bool {
	return strings.Contains(context, "://") || strings.HasPrefix(context, "git@")
}

// C011: build.target references a nonexistent build stae
func checkBuildTarget(svc compose.Service, df *dockerfile.File) []analyzer.Finding {
	if svc.Build.Target == "" {
		return nil
	}
	for _, stage := range df.Stages {
		if stage.Name == svc.Build.Target {
			return nil
		}
	}
	return []analyzer.Finding{{
		Line:     svc.Line,
		Severity: analyzer.Warning,
		Category: analyzer.CategoryPerformance,
		RuleID:   "C011",
		Message:  fmt.Sprintf("Service %q's build.target %q is not a stage in its Dockerfile.", svc.Name, svc.Build.Target),
		Detail:   "`docker compose build` will fail for this service. This is likely a stale reference after the Dockerfile's stages were renamed or reordered.",
	}}
}

// C012: compose overrides USER to root against a hardened Dockerfile
func checkUserOverride(svc compose.Service, df *dockerfile.File) []analyzer.Finding {
	if svc.User == "" || !dockerfile.IsRootUser(svc.User) {
		return nil
	}
	if dockerfile.IsRootUser(df.FinalStageUser()) {
		return nil // Dockerfile already runs as root - nothing to override
	}
	return []analyzer.Finding{{
		Line:     svc.Line,
		Severity: analyzer.Warning,
		Category: analyzer.CategorySecurity,
		RuleID:   "C012",
		Message:  fmt.Sprintf("Service %q sets user: %s, overriding its Dockerfile's non-root USER.", svc.Name, svc.User),
		Detail:   "The Dockerfile this service builds from deliberately runs as a non-root user; this compose file's `user:` setting overrides that back to root at container start, silently undoing the hardening.",
	}}
}
