// P004: ADD used where COPY would suffice
var archiveExtensions = []string{".tar", ".tar.gz", ".tgz", ".tar.bz2", ".tbz2", ".tar.xz", ".txz", ".zip"}

func checkAddVsCopy(instr dockerfile.Instruction) []analyzer.Finding {
	_, positional := dockerfile.SplitFlags(instr.Args)
	if len(positional) < 2 {
		return nil
	}
	sources := positional[:len(positional)-1]
	for _, src := range sources {
		if dockerfile.IsURL(src) || hasArchiveExtension(src) {
			return nil // legitimate ADD use: remote fetch or local archive auto-extraction
		}
	}
	return []analyzer.Finding{{
		Line:     instr.Line,
		Severity: analyzer.Info,
		Category: analyzer.CategoryPerformance,
		RuleID:   "P004",
		Message:  "ADD used where COPY would suffice.",
		Detail:   "ADD's implicit URL-fetch and tar-extraction behavior isn't needed here; COPY is simpler and more predictable.",
	}}
}

func hasArchiveExtension(s string) bool {
	lower := strings.ToLower(s)
	for _, ext := range archiveExtensions {
		if strings.HasSuffix(lower, ext) {
			return true
		}
	}
	return false
}

// Shared by P006 (explicitly copied in) and P011 (missing from .dockerignore on a broad COPY)
var bloatDirPatterns = []string{"node_modules", ".git", "__pycache__", ".venv"}

// P006: heavy/generated directory copied from the build context.
func checkHeavyDirCopy(instr dockerfile.Instruction) []analyzer.Finding {
	_, positional := dockerfile.SplitFlags(instr.Args)
	if len(positional) < 2 {
		return nil
	}
	sources := positional[:len(positional)-1]
	for _, src := range sources {
		for _, pat := range bloatDirPatterns {
			if strings.Contains(src, pat) {
				return []analyzer.Finding{{
					Line:     instr.Line,
					Severity: analyzer.Warning,
					Category: analyzer.CategoryPerformance,
					RuleID:   "P006",
					Message:  fmt.Sprintf("Copies %q from the build context into the image.", src),
					Detail:   "Host-generated or dependency directories bloat the image and break reproducibility; regenerate them inside the build instead, or exclude via .dockerignore.",
				}}
			}
		}
	}
	return nil
}

// P011: broad COPY with no (or insufficient) .dockerignore
func checkDockerignore(df *dockerfile.File, ctx analyzer.Context) []analyzer.Finding {
	if !df.HasBroadCopy() {
		return nil
	}

	content, ok := ctx.ReadSibling(".dockerignore")
	if !ok {
		return []analyzer.Finding{{
			Line:     1,
			Severity: analyzer.Info,
			Category: analyzer.CategoryPerformance,
			RuleID:   "P011",
			Message:  "Broad COPY with no .dockerignore file.",
			Detail:   "Without a .dockerignore, the entire build context (including node_modules, .git, and other large or generated directories) is sent to the daemon and can invalidate the build cache on every unrelated change.",
		}}
	}

	patterns := dockerignore.Parse(content)
	var missing []string
	for _, p := range bloatDirPatterns {
		if !dockerignore.Excludes(patterns, p) {
			missing = append(missing, p)
		}
	}
	if len(missing) == 0 {
		return nil
	}
	return []analyzer.Finding{{
		Line:     1,
		Severity: analyzer.Info,
		Category: analyzer.CategoryPerformance,
		RuleID:   "P011",
		Message:  fmt.Sprintf(".dockerignore doesn't exclude: %s.", strings.Join(missing, ", ")),
		Detail:   "A broad COPY sends anything not excluded to the build context, inflating upload size and cache invalidation surface.",
	}}
}

// P017: COPY/ADD source missing from the build context
func checkMissingCopySource(df *dockerfile.File, ctx analyzer.Context) []analyzer.Finding {
	if ctx.Dir == "" {
		return nil
	}
	var findings []analyzer.Finding
	for _, instr := range df.Instructions {
		if instr.Cmd != "COPY" && instr.Cmd != "ADD" {
			continue
		}
		flags, positional := dockerfile.SplitFlags(instr.Args)
		if _, ok := flags["--from"]; ok {
			continue // source is another build stage or an external image, not the local filesystem
		}
		if len(positional) < 2 {
			continue
		}
		for _, src := range positional[:len(positional)-1] {
			if dockerfile.IsBroadCopySource(src) || dockerfile.IsURL(src) {
				continue
			}
			if sourceExists(ctx.Dir, src) {
				continue
			}
			findings = append(findings, analyzer.Finding{
				Line:     instr.Line,
				Severity: analyzer.Warning,
				Category: analyzer.CategoryPerformance,
				RuleID:   "P017",
				Message:  fmt.Sprintf("%s source %q was not found in the build context.", instr.Cmd, src),
				Detail:   "This path doesn't exist relative to the Dockerfile's directory, so `docker build` will fail here. If it's generated by a step outside this Dockerfile (a pre-build script, a symlink not yet created, ...), this is a false positive - dockscribe only sees what's on disk right now.",
			})
		}
	}
	return findings
}

func sourceExists(dir, src string) bool {
	full := filepath.Join(dir, filepath.FromSlash(src))
	if strings.ContainsAny(src, "*?[") {
		matches, err := filepath.Glob(full)
		return err == nil && len(matches) > 0
	}
	_, err := os.Stat(full)
	return err == nil
}
